-- PageLens baseline schema (plan section 6).
-- Conventions:
--   * All timestamps are TIMESTAMPTZ and stored in UTC.
--   * Raw API payloads / extra metrics are TEXT holding JSON, which keeps the SQL portable to SQLite.
--   * Natural Instagram ids carry UNIQUE constraints so sync jobs can upsert idempotently.

CREATE TABLE ig_account (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ig_user_id        VARCHAR(64)  NOT NULL UNIQUE,
    -- Which Meta API setup this account is connected through: INSTAGRAM_LOGIN (graph.instagram.com)
    -- or FACEBOOK_LOGIN (graph.facebook.com, requires a linked Facebook Page).
    login_type        VARCHAR(32)  NOT NULL,
    facebook_page_id  VARCHAR(64),
    username          VARCHAR(255) NOT NULL,
    display_name      VARCHAR(255),
    account_type      VARCHAR(32),
    followers_count   BIGINT,
    media_count       BIGINT,
    -- ACTIVE, NEEDS_RECONNECT (token invalid/expired/revoked), DISCONNECTED
    status            VARCHAR(32)  NOT NULL DEFAULT 'ACTIVE',
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ig_token (
    account_id        BIGINT       PRIMARY KEY REFERENCES ig_account (id) ON DELETE CASCADE,
    -- AES-GCM: nonce || ciphertext || tag. The key lives outside the database (env var / OS keychain).
    encrypted_token   BYTEA        NOT NULL,
    key_version       INT          NOT NULL DEFAULT 1,
    token_type        VARCHAR(32)  NOT NULL,
    scopes            TEXT,
    expires_at        TIMESTAMPTZ,
    last_refreshed_at TIMESTAMPTZ,
    -- VALID, EXPIRING, INVALID
    status            VARCHAR(32)  NOT NULL DEFAULT 'VALID',
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE media (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id        BIGINT       NOT NULL REFERENCES ig_account (id) ON DELETE CASCADE,
    ig_media_id       VARCHAR(64)  NOT NULL UNIQUE,
    media_type        VARCHAR(32)  NOT NULL,
    media_product_type VARCHAR(32),
    caption           TEXT,
    permalink         TEXT,
    thumbnail_url     TEXT,
    posted_at         TIMESTAMPTZ,
    is_story          BOOLEAN      NOT NULL DEFAULT FALSE,
    raw_json          TEXT,
    first_seen_at     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_media_account_posted ON media (account_id, posted_at DESC);

-- One row per insights fetch, so performance over a post's lifetime can be charted.
-- NULL means "not returned by the API", never zero.
CREATE TABLE media_insight_snapshot (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    media_id          BIGINT       NOT NULL REFERENCES media (id) ON DELETE CASCADE,
    captured_at       TIMESTAMPTZ  NOT NULL,
    reach             BIGINT,
    views             BIGINT,
    likes             BIGINT,
    comments          BIGINT,
    shares            BIGINT,
    saves             BIGINT,
    follows           BIGINT,
    extra_metrics     TEXT,
    UNIQUE (media_id, captured_at)
);

CREATE TABLE comment (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    media_id          BIGINT       NOT NULL REFERENCES media (id) ON DELETE CASCADE,
    ig_comment_id     VARCHAR(64)  NOT NULL UNIQUE,
    parent_id         BIGINT       REFERENCES comment (id) ON DELETE CASCADE,
    username          VARCHAR(255),
    text              TEXT,
    like_count        BIGINT,
    posted_at         TIMESTAMPTZ,
    hidden            BOOLEAN      NOT NULL DEFAULT FALSE,
    first_seen_at     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_comment_media ON comment (media_id, posted_at);

CREATE TABLE account_daily_metric (
    account_id        BIGINT       NOT NULL REFERENCES ig_account (id) ON DELETE CASCADE,
    day               DATE         NOT NULL,
    reach             BIGINT,
    views             BIGINT,
    followers_count   BIGINT,
    follower_delta    BIGINT,
    profile_views     BIGINT,
    extra_metrics     TEXT,
    captured_at       TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (account_id, day)
);

CREATE TABLE audience_snapshot (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id        BIGINT       NOT NULL REFERENCES ig_account (id) ON DELETE CASCADE,
    captured_at       TIMESTAMPTZ  NOT NULL,
    -- country, city, age, gender
    dimension         VARCHAR(32)  NOT NULL,
    dim_key           VARCHAR(255) NOT NULL,
    value             BIGINT       NOT NULL,
    UNIQUE (account_id, captured_at, dimension, dim_key)
);

CREATE TABLE sync_run (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id        BIGINT       REFERENCES ig_account (id) ON DELETE CASCADE,
    job_type          VARCHAR(64)  NOT NULL,
    -- ui, mcp, scheduler
    triggered_by      VARCHAR(32)  NOT NULL,
    correlation_id    VARCHAR(128),
    started_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at       TIMESTAMPTZ,
    -- RUNNING, SUCCEEDED, FAILED
    status            VARCHAR(32)  NOT NULL,
    items_fetched     INT          NOT NULL DEFAULT 0,
    error_message     TEXT
);
CREATE INDEX idx_sync_run_account_started ON sync_run (account_id, started_at DESC);

CREATE TABLE api_call_log (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id        BIGINT       REFERENCES ig_account (id) ON DELETE SET NULL,
    correlation_id    VARCHAR(128),
    http_method       VARCHAR(8)   NOT NULL,
    -- Path and non-secret query params only; access tokens are masked before storage.
    endpoint          TEXT         NOT NULL,
    http_status       INT,
    duration_ms       BIGINT,
    rate_usage_header TEXT,
    error_code        VARCHAR(64),
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_api_call_log_created ON api_call_log (created_at DESC);

CREATE TABLE audit_log (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- ui, mcp, scheduler
    actor             VARCHAR(32)  NOT NULL,
    action            VARCHAR(64)  NOT NULL,
    target            TEXT,
    payload_summary   TEXT,
    dry_run           BOOLEAN      NOT NULL DEFAULT FALSE,
    outcome           VARCHAR(32),
    correlation_id    VARCHAR(128),
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_audit_log_created ON audit_log (created_at DESC);
