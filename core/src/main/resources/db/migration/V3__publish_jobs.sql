-- Phase 3: publishing jobs. One row per publish request; the container ids are stored as soon as Meta returns
-- them, so a retry or a restart checks the existing container instead of creating (or publishing) a second one.

CREATE TABLE publish_job (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id           BIGINT       NOT NULL REFERENCES ig_account (id) ON DELETE CASCADE,
    -- Client-supplied key: the same key never starts a second job (double-click, retried request).
    idempotency_key      VARCHAR(128) NOT NULL UNIQUE,
    -- IMAGE, REEL, STORY, CAROUSEL
    kind                 VARCHAR(16)  NOT NULL,
    caption              TEXT,
    -- JSON: [{"type":"IMAGE|VIDEO","url":"...","uploadId":"..."}] and kind-specific options.
    items_json           TEXT         NOT NULL,
    item_count           INT          NOT NULL,
    options_json         TEXT,
    -- ui, mcp
    actor                VARCHAR(16)  NOT NULL,
    -- QUEUED, CREATING, PROCESSING, PUBLISHING, PUBLISHED, FAILED
    status               VARCHAR(16)  NOT NULL,
    child_container_ids  TEXT,
    container_id         VARCHAR(64),
    ig_media_id          VARCHAR(64),
    permalink            TEXT,
    error_message        TEXT,
    correlation_id       VARCHAR(128),
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at         TIMESTAMPTZ
);
CREATE INDEX idx_publish_job_account_created ON publish_job (account_id, created_at DESC);
CREATE INDEX idx_publish_job_status ON publish_job (status);
